# These isolated tests exercise outcomes and boundaries, not a browser or the
# production scheduler. unittest permits the small pure module to run without
# loading Flask; pytest also collects the same cases in the normal CI suite.
import hashlib
import json
import sys
import tempfile
import time
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from engines.game_ui_review_lab import evaluate_game_ui_review


class GameUIReviewBoundaries(unittest.TestCase):
    @staticmethod
    def source_fixture():
        screens = [{"screen_id": name, "route": "/" + name.lower(),
                    "primary_content": ["SYNTHETIC"], "actions": ["SYNTHETIC"]}
                   for name in ("HOME", "LIVE", "MATCHES", "MATCH", "PICKS")]
        contract = {"contract": "NEMESIS-CREATIVE-DESIGN-1", "screens": screens,
                    "policy": {"functional_pass_implies_design_match": False, "automatic_publication": False}}
        names = ("mark-256", "ocean-768", "wireframe-480", "ocean-1600", "wireframe-960")
        manifest = {"family": "owner-approved-20261023", "assets": [
            {"file": "nemesis-approved-" + name + ".webp", "bytes": 1000, "sha256": "a" * 64}
            for name in names]}
        token = ":root{--synthetic:.1}\n"
        digest = hashlib.sha256(token.encode()).hexdigest()
        return {
            "reference_images/design_contracts.json": json.dumps(contract),
            "static/img/approved-identity/manifest.json": json.dumps(manifest),
            "tools/visual_css_sources.json": '["design-tokens.css"]',
            "static/design-tokens.css": token,
            "static/product-system.css": "/* Generated by npm run build:css; source-sha256: " + digest + " */\n:root{--synthetic:.1}\n",
        }

    @staticmethod
    def row(result, identifier):
        return next(row for row in result["results"] if row["id"] == identifier)

    def test_missing_sources_record_unknown_without_writes(self):
        with tempfile.TemporaryDirectory() as folder:
            result = evaluate_game_ui_review(folder)
            self.assertEqual(list(Path(folder).rglob("*")), [])
        self.assertEqual(len(result["results"]), 7)
        self.assertEqual({row["state"] for row in result["results"]}, {"UNKNOWN"})
        self.assertFalse(result["browser_executed"])
        self.assertFalse(result["production_certified"])

    def test_snapshot_reuse_performs_no_filesystem_or_network_reads(self):
        with patch.object(Path, "open", side_effect=AssertionError("unexpected IO")), \
             patch("socket.socket", side_effect=AssertionError("unexpected socket")), \
             patch("socket.getaddrinfo", side_effect=AssertionError("unexpected DNS")):
            result = evaluate_game_ui_review("not-used", input_snapshot=self.source_fixture())
        self.assertEqual(result["external_calls"], 0)
        self.assertTrue(all(row["executed"] for row in result["results"]))

    def test_changed_source_invalidates_bundle_and_keeps_proposal_identity(self):
        fixture = self.source_fixture()
        baseline = evaluate_game_ui_review("not-used", input_snapshot=fixture)
        self.assertEqual(self.row(baseline, "technical_art")["checks"][0]["state"], "PASS")
        self.assertEqual(self.row(baseline, "technical_art")["state"], "UNKNOWN")
        fixture["static/design-tokens.css"] += "/* changed */"
        first = self.row(evaluate_game_ui_review("not-used", input_snapshot=fixture), "technical_art")
        fixture["static/design-tokens.css"] += "/* changed again */"
        second = self.row(evaluate_game_ui_review("not-used", input_snapshot=fixture), "technical_art")
        self.assertEqual(first["state"], "FAIL")
        self.assertNotEqual(first["source_fingerprint"], second["source_fingerprint"])
        self.assertEqual(first["findings"][0]["proposal"], second["findings"][0]["proposal"])

    def test_budget_regression_is_a_finding_without_invented_web_metrics(self):
        fixture = self.source_fixture()
        manifest = json.loads(fixture["static/img/approved-identity/manifest.json"])
        manifest["assets"][0]["bytes"] = 180000
        fixture["static/img/approved-identity/manifest.json"] = json.dumps(manifest)
        row = self.row(evaluate_game_ui_review("not-used", input_snapshot=fixture), "graphics_performance")
        self.assertEqual(row["state"], "FAIL")
        self.assertEqual(row["checks"][1]["state"], "UNKNOWN")
        self.assertNotIn("lcp", row)

    def test_untrusted_manifest_path_is_not_read_or_exposed(self):
        fixture = self.source_fixture()
        manifest = json.loads(fixture["static/img/approved-identity/manifest.json"])
        manifest["assets"][0]["file"] = "../../private/do-not-read-secret"
        fixture["static/img/approved-identity/manifest.json"] = json.dumps(manifest)
        with patch.object(Path, "open", side_effect=AssertionError("unexpected path read")):
            result = evaluate_game_ui_review("not-used", input_snapshot=fixture)
        self.assertEqual(self.row(result, "graphics_performance")["state"], "UNKNOWN")
        self.assertNotIn("do-not-read-secret", json.dumps(result))

    def test_malformed_nested_contract_and_forged_pass_do_not_certify(self):
        fixture = self.source_fixture()
        fixture["reference_images/design_contracts.json"] = json.dumps({
            "contract": "NEMESIS-CREATIVE-DESIGN-1", "screens": [{"screen_id": []}], "policy": ["PASS"]})
        result = evaluate_game_ui_review("not-used", input_snapshot=fixture,
                                       evidence={"all_pass": True, "browser_executed": True, "production_certified": True})
        self.assertEqual(len(result["results"]), 7)
        self.assertFalse(result["unverified_evidence_promoted"])
        self.assertFalse(result["supplied_evidence_used"])
        self.assertFalse(result["browser_executed"])
        self.assertEqual(self.row(result, "visual_qa_director")["state"], "UNKNOWN")

    def test_expired_budget_does_not_claim_execution(self):
        with patch.object(Path, "open", side_effect=AssertionError("unexpected IO")):
            result = evaluate_game_ui_review("not-used", input_snapshot=self.source_fixture(), deadline=time.monotonic() - 1)
        self.assertTrue(result["time_budget_exhausted"])
        self.assertFalse(any(row["executed"] for row in result["results"]))
        self.assertEqual(result["findings"], [])

    def test_budget_expiring_during_read_does_not_credit_seven_reviews(self):
        calls = []
        def clock():
            calls.append(None)
            return 1.0 if len(calls) < 4 else 11.0
        with patch("engines.game_ui_review_lab.time.monotonic", side_effect=clock):
            result = evaluate_game_ui_review("not-used", input_snapshot=self.source_fixture(), deadline=10.0)
        self.assertTrue(result["time_budget_exhausted"])
        self.assertFalse(any(row["executed"] for row in result["results"]))
        self.assertEqual(result["findings"], [])
        loaded = {"state": "RECENT", "receipt": {"contract": "NEMESIS-NATIVE-WORKFORCE-REVIEW-V1"}, "results": result["results"]}
        self.assertEqual(build_game_ui_lab(review=loaded)["reviewed_count"], 0)

    def test_stale_receipt_and_partial_review_do_not_activate_other_roles(self):
        results = evaluate_game_ui_review("not-used", input_snapshot=self.source_fixture())["results"]
        loaded = {"state": "STALE", "receipt": {"contract": "NEMESIS-NATIVE-WORKFORCE-REVIEW-V1",
                  "finished_at_madrid": "2026-10-29T15:00:00+01:00", "run_id": "SIMULATED_QA"}, "results": results}
        stale = build_game_ui_lab(review=loaded)
        self.assertEqual(stale["state"], "PLANNED_NOT_EXECUTED")
        self.assertTrue(all(item["execution_state"] == "UNVERIFIED" for item in stale["disciplines"]))
        loaded.update(state="RECENT", results=[results[0]])
        recent = build_game_ui_lab(review=loaded)
        self.assertEqual(recent["reviewed_count"], 1)
        self.assertEqual(sum(item["execution_state"] == "STATIC_PARTIAL" for item in recent["disciplines"]), 1)
        self.assertEqual(recent["autonomous_agents_started"], 0)

    def test_company_projection_is_read_only_and_does_not_credit_skipped_reviews(self):
        from engines.company_operating_system_engine import WORKER_BLUEPRINTS
        core = {"worker_name": WORKER_BLUEPRINTS[0][0], "state": "UNKNOWN", "executed": True,
                "proposal": "SYNTHETIC: revisar evidencia pendiente", "limitation": "SYNTHETIC: estática parcial",
                "checks": [{"state": "PASS", "result": "SYNTHETIC_STATIC_CHECK"}, {"state": []}],
                "evidence": [{"path": "templates/base.html", "sha256": "b" * 64, "state": "READ", "source": "NEVER_EXPOSE_SOURCE"},
                             {"path": "../../private/NEVER_EXPOSE_PATH", "state": "READ"}]}
        loaded = {"state": "RECENT", "receipt": {"contract": "NEMESIS-NATIVE-WORKFORCE-REVIEW-V1",
                  "finished_at_madrid": "2026-10-29T15:00:00+01:00"}, "results": [core]}
        fake = SimpleNamespace(load_native_workforce_receipt=lambda *args, **kwargs: loaded)
        with patch.dict(sys.modules, {"engines.product_review_system_engine": fake}), \
             patch("engines.company_workforce_receipts_engine.master_cron_receipt", return_value={}), \
             patch.object(Path, "open", side_effect=AssertionError("unexpected IO")), \
             patch("socket.socket", side_effect=AssertionError("unexpected socket")):
            recent = build_company_os_summary()
            core["executed"] = False
            skipped = build_company_os_summary()
            core["executed"] = True
            loaded["state"] = "STALE"
            stale = build_company_os_summary()
        self.assertEqual(recent["native_workforce_review"]["reviewed_core_count"], 1)
        review = recent["workers"][0]["static_review"]
        self.assertEqual(review["proposal"], core["proposal"])
        self.assertEqual(review["checks"], [{"state": "PASS", "detail": "SYNTHETIC_STATIC_CHECK"}])
        self.assertEqual(len(review["evidence"]), 1)
        self.assertNotIn("NEVER_EXPOSE", json.dumps(recent))
        self.assertEqual(skipped["native_workforce_review"]["reviewed_core_count"], 0)
        self.assertEqual(stale["execution_state"], "UNVERIFIED")
